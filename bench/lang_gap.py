"""English against Korean on parallel sets: the same items, by id, in two languages, paired per engine.

    uv run python bench/lang_gap.py bench/runs/massive-en bench/runs/massive-ko --out reports/lang-gap.md
    uv run python bench/lang_gap.py bench/runs/questions bench/runs/questions_ko

The two sets must carry the same item ids and the same expected answers (make_sets.py's massive-en / massive-ko, or
the hand-written 30-ticket pair). For every engine logged in both directories, each decision graded in both
languages is one pair: `b` = right only in the first set, `c` = right only in the second, `p` = the exact McNemar
p value. A gap with p >= 0.05 is not told apart from no gap.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import score


def gap_rows(a: tuple[list[dict], dict[str, list[dict]]],
             b: tuple[list[dict], dict[str, list[dict]]]) -> list[tuple[str, int, int, int, int, int]]:
    """(engine, paired decisions, right in a, right in b, only a, only b) per engine logged in both sets."""
    items_a, runs_a = a
    items_b, runs_b = b
    gold_a = {(it["id"], q): v for it in items_a for q, v in it["expected"].items()}
    gold_b = {(it["id"], q): v for it in items_b for q, v in it["expected"].items()}
    if gold_a != gold_b:
        raise SystemExit("the two sets differ in item ids or expected answers; they are not parallel")
    rows = []
    for e in sorted(runs_a.keys() & runs_b.keys()):
        ra = {k: score.is_right(*v) for k, v in score.graded(items_a, runs_a[e]).items()}
        rb = {k: score.is_right(*v) for k, v in score.graded(items_b, runs_b[e]).items()}
        both = ra.keys() & rb.keys()
        if not both:
            continue
        rows.append((e, len(both), sum(ra[k] for k in both), sum(rb[k] for k in both),
                     sum(ra[k] and not rb[k] for k in both), sum(rb[k] and not ra[k] for k in both)))
    return rows


def load(d: Path) -> tuple[list[dict], dict[str, list[dict]]]:
    _, items, logs = score.load_dir(d)
    return items, {e: recs for e, (_, recs) in logs.items()}


def table(name_a: str, name_b: str, rows: list[tuple[str, int, int, int, int, int]]) -> list[str]:
    lines = [f"## {name_a} vs {name_b}", "",
             f"| engine | paired | {name_a} | {name_b} | gap (pt) | b | c | p |", "|---|---|---|---|---|---|---|---|"]
    for e, n, ra, rb, only_a, only_b in sorted(rows, key=lambda r: (r[3] - r[2]) / r[1]):
        lines.append(f"| {e} | {n} | {score.ratio(ra, n)} | {score.ratio(rb, n)} | {100 * (rb - ra) / n:+.1f} "
                     f"| {only_a} | {only_b} | {score.p_cell(score.mcnemar_exact(only_a, only_b))} |")
    return lines + [""]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("a", type=Path, help="bench/runs/<first set>, e.g. massive-en")
    ap.add_argument("b", type=Path, help="bench/runs/<parallel set>, e.g. massive-ko")
    ap.add_argument("--out", type=Path, help="also write the table here")
    args = ap.parse_args()
    text = "\n".join(["# Language gap", "", "Generated by `bench/lang_gap.py` from the raw logs; see its docstring.",
                      ""] + table(args.a.name, args.b.name, gap_rows(load(args.a), load(args.b))))
    if args.out:
        args.out.write_text(text)
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
