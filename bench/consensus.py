"""Label-noise candidates: decisions the strongest engines all answer the same way, against the gold label.

    uv run python bench/consensus.py bench/runs/klue-ynat bench/runs/nsmc --out reports/consensus.md

For each set, the `--top` engines with the best accuracy (excluding `--skip`, e.g. engines trained on the set) form
a panel. A decision every panel engine answers with the same wrong decision is a candidate: the gold label may be
wrong, or the question may be ambiguous. Most of them are not engine mistakes a better engine would fix, so the
share of candidates bounds what any engine can show on the set, and an accuracy that leaves them out says how the
engines compare on the rest. The candidates are listed for a human to judge; nothing here changes a gold label.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import score


def panel_and_candidates(items: list[dict], runs: dict[str, list[dict]], top: int,
                         skip: set[str]) -> tuple[list[str], dict[tuple[str, str], str]]:
    """(panel engines, {(item, question): the decision every panel engine made instead of gold})."""
    graded = {e: score.graded(items, recs) for e, recs in runs.items()}
    acc = {e: sum(score.is_right(*v) for v in g.values()) / len(g) for e, g in graded.items() if g and e not in skip}
    panel = sorted(acc, key=lambda e: (-acc[e], e))[:top]
    candidates = {}
    for key in ((it["id"], qid) for it in items for qid in it["expected"]):
        if not panel or any(key not in graded[e] for e in panel):
            continue
        picks = {str(score.decide(q, a, rule)) for q, a, _, rule in (graded[e][key] for e in panel)}
        if len(picks) == 1 and not score.is_right(*graded[panel[0]][key]):
            candidates[key] = picks.pop()
    return panel, candidates


def section(d: Path, top: int, skip: set[str]) -> list[str]:
    _, items, logs = score.load_dir(d)
    runs = {e: recs for e, (_, recs) in logs.items()}
    panel, cand = panel_and_candidates(items, runs, top, skip)
    by_id = {it["id"]: it for it in items}
    decisions = sum(len(it["expected"]) for it in items)
    lines = [f"## {d.name}", "",
             (f"Panel ({len(panel)}): {', '.join(panel)}. {len(cand)} of {decisions} decisions "
              f"({len(cand) / decisions:.1%}) are answered the same wrong way by the whole panel."), "",
             "| engine | accuracy | accuracy without the candidates |", "|---|---|---|"]
    for e in sorted(runs, key=lambda e: e not in panel):
        g = score.graded(items, runs[e])
        if not g:
            continue
        rest = {k: v for k, v in g.items() if k not in cand}
        lines.append(f"| {e} | {score.ratio(sum(score.is_right(*v) for v in g.values()), len(g))} "
                     f"| {score.ratio(sum(score.is_right(*v) for v in rest.values()), len(rest))} |")
    lines += ["", "| item | question | gold | panel | input |", "|---|---|---|---|---|"]
    for (iid, qid), pick in sorted(cand.items()):
        text = score_text(by_id[iid]["state"])
        lines.append(f"| {iid} | {qid} | {by_id[iid]['expected'][qid]} | {pick} | {text} |")
    return lines + [""]


def score_text(state: object, limit: int = 100) -> str:
    """One table cell of the item's input: one line, pipes escaped, cut at `limit` characters."""
    text = " ".join(str(state).split()).replace("|", "\\|")
    return text if len(text) <= limit else text[:limit - 1] + "…"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dirs", type=Path, nargs="+", help="bench/runs/<set>")
    ap.add_argument("--top", type=int, default=8, help="panel size (default 8)")
    ap.add_argument("--skip", default="", help="comma-separated engines kept out of the panel")
    ap.add_argument("--out", type=Path, help="also write the tables here")
    args = ap.parse_args()
    skip = {e for e in args.skip.split(",") if e}
    text = "\n".join(["# Label-noise candidates", "", ("Generated by `bench/consensus.py` from the raw logs; see its "
                                                        "docstring for the method."), ""]
                     + [line for d in args.dirs for line in section(d, args.top, skip)])
    if args.out:
        args.out.write_text(text)
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
